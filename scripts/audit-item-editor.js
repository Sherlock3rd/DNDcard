const clone = (value) => JSON.parse(JSON.stringify(value));
function boot(saved = {}) {
  const dom = new JSDOM(html, { url: "https://example.test/#item-library", runScripts: "outside-only", pretendToBeVisual: true });
  const w = dom.window;
  w.structuredClone = structuredClone;
  w.scrollTo = () => {};
  const errors = [];
  w.addEventListener("error", (event) => errors.push(event.error));
  w.IntersectionObserver = class { observe() {} disconnect() {} };
  w.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  w.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new w.Event("close")); };
  w.confirm = () => true;
  w.URL.createObjectURL = () => "blob:test";
  w.URL.revokeObjectURL = () => {};
  const downloads = [], opened = [];
  w.HTMLAnchorElement.prototype.click = function () { downloads.push({ href: this.href, filename: this.download }); };
  w.open = (...args) => { opened.push(args); return null; };
  for (const [key, value] of Object.entries(saved)) w.localStorage.setItem(key, value);
  for (const script of scripts) vm.runInContext(fs.readFileSync(path.join(root, script), "utf8"), dom.getInternalVMContext(), { filename: script });
  return { dom, w, errors, downloads, opened, run: (code) => vm.runInContext(code, dom.getInternalVMContext()) };
}
